// Generates src/data/countryEndonyms.ts — each country's native-language name(s)
// (endonym), where they differ from the English exonym the app uses. Shown in
// the Learn-mode country widget above the population. Source: mledoze/countries
// `name.native` (the same authoritative dataset COUNTRY_FACTS is built from).
// Never invented — a country whose native name is the English name is omitted.
// Re-run: node scripts/build-country-endonyms.mjs  (needs raw.githubusercontent egress)

import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const URL = "https://raw.githubusercontent.com/mledoze/countries/master/dist/countries.json";
const res = await fetch(URL);
if (!res.ok) throw new Error(`mledoze fetch failed: ${res.status}`);
const countries = await res.json();

const norm = (s) => (s || "").normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase().replace(/[^a-z0-9]/g, "");

const out = {};
for (const c of countries) {
  const cca2 = c.cca2;
  const english = c.name?.common;
  const native = c.name?.native; // { lang3: { official, common } }
  if (!cca2 || !english || !native) continue;
  // Collect distinct native common names that differ from the English name.
  const names = [];
  for (const lang of Object.keys(native)) {
    const n = native[lang]?.common?.trim();
    if (!n) continue;
    if (norm(n) === norm(english)) continue; // same as English → nothing to show
    if (!names.some((x) => norm(x) === norm(n))) names.push(n);
  }
  if (names.length) out[cca2] = names.join(" / ");
}

const lines = Object.keys(out).sort().map((k) => `  ${k}: ${JSON.stringify(out[k])},`).join("\n");
const ts = `// Auto-generated by scripts/build-country-endonyms.mjs — DO NOT EDIT MANUALLY
// A country's native-language name(s) (endonym), where they differ from the
// English exonym the app uses as the canonical name. Shown in the Learn-mode
// country widget, above the population. Source: mledoze/countries name.native.
// Re-run: node scripts/build-country-endonyms.mjs

/** ISO 3166-1 alpha-2 → native-language name(s), only where they differ from English. */
export const COUNTRY_ENDONYMS: Readonly<Record<string, string>> = {
${lines}
};
`;
writeFileSync(join(root, "src", "data", "countryEndonyms.ts"), ts);
console.log(`✓ country endonyms: ${Object.keys(out).length} of ${countries.length} countries have a distinct native name.`);
console.log("  samples:", ["DE","JP","ES","GR","RU","CN","EG","SA"].map(k=>`${k}=${out[k]||"—"}`).join("  "));
