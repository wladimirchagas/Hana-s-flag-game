// Generate src/data/polityContinents.ts — the continent a historical polity's LAND is on.
//
// Re-run: node scripts/build-polity-continents.mjs
//
// Why this file exists
// --------------------
// The Learn-mode flag grid groups an era's polities by continent. That continent used to
// come from the polity's curated registry entry or — when it had none — from whichever
// country it BORROWED ITS FLAG FROM. For a colony routed to its ruling power that meant
// importing the ruler's continent, and the 1914 grid filed Togoland, Kamerun, German
// South-West Africa, German East Africa, Anglo-Egyptian Sudan, British East Africa,
// Southern Rhodesia and Spanish Morocco under EUROPE. Reported by the owner with a
// screenshot, 2026-08 ("togoland is not in europe").
//
// Polities with no curated region label had the opposite problem: 518 of them showed no
// continent at all and fell into the grid's "Other" bucket.
//
// Both are answered by the geometry, which is already bundled and cannot be argued with:
// this generator reads each polity's own polygons out of public/historical-maps/*.geojson
// and works out which continent that land is on, using the SAME Natural Earth basemap
// (public/countries-50m.json) every map in the app draws. Nothing is invented — the
// continent is measured, not written.
//
// It only fills GAPS. A polity with a curated `continent` in POLITY_REGISTRY /
// ERA_OVERRIDES keeps it (those labels are finer-grained — "Eurasian Steppe", "Levant",
// "Mesoamerica" — and drive the detail panel's Region row). check-era-continents.mjs is
// what verifies those curated labels against the same measurement.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { continentSplit, polityRings } from "./lib/polity-geography.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const R = (p) => resolve(__dirname, p);

const { ERAS, polityInfo } = await import(R("../src/lib/historicalEras.ts"));

/** eraId → (NAME → continent), only for polities with no curated continent. */
const perEra = new Map();
for (const era of ERAS) {
  if (!era.dataUrl) continue;
  const geo = JSON.parse(readFileSync(R(`../public/${era.dataUrl}`), "utf8"));
  const forEra = new Map();
  for (const [name, rings] of polityRings(geo)) {
    if (polityInfo(name, era.id).continent) continue; // curated label wins
    const split = continentSplit(rings);
    if (split.length === 0) continue;
    forEra.set(name, split[0].continent);
  }
  perEra.set(era.id, forEra);
}

// Most polity names sit on the same continent in every era they appear in, so the bulk of
// the table is keyed by NAME alone. Only a name whose land MOVES between eras — or that
// two different eras use for two different places — needs a per-era row.
const seen = new Map();
for (const forEra of perEra.values()) {
  for (const [name, continent] of forEra) {
    const set = seen.get(name) ?? new Set();
    set.add(continent);
    seen.set(name, set);
  }
}

const byName = new Map();
const byEraName = new Map();
for (const [name, continents] of seen) {
  if (continents.size === 1) byName.set(name, [...continents][0]);
}
for (const [eraId, forEra] of perEra) {
  for (const [name, continent] of forEra) {
    if (byName.get(name) === continent) continue;
    byEraName.set(`${eraId}|${name}`, continent);
  }
}

const quote = (s) => JSON.stringify(s);
const rows = (entries) =>
  [...entries]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([k, v]) => `  [${quote(k)}, ${quote(v)}],`)
    .join("\n");

const out = `// AUTO-GENERATED by scripts/build-polity-continents.mjs — do not edit by hand.
// Re-run: node scripts/build-polity-continents.mjs
//
// The continent each historical polity's LAND is on, measured from the polity's own
// polygons in public/historical-maps/*.geojson against the app's bundled Natural Earth
// basemap (public/countries-50m.json).
//
// This is the FALLBACK the Learn-mode flag grid groups by when a polity has no curated
// region label in POLITY_REGISTRY / ERA_OVERRIDES — see \`polityContinent()\` in
// src/lib/historicalEras.ts. It exists because the grid used to fall back to the
// continent of whichever country the polity BORROWED ITS FLAG FROM, which filed every
// German, British, Spanish and French colony in 1914 under Europe.
//
// HARD RULE (CLAUDE.md, "A polity's continent is where its land is"): never hand-edit
// this file, and never give a polity a continent its own land is not on. A curated label
// that disagrees with the land is a bug in the label — scripts/check-era-continents.mjs
// fails the build on one.

/** Polity NAME → continent, for names whose land is on one continent in every era. */
export const POLITY_CONTINENT: ReadonlyMap<string, string> = new Map([
${rows(byName)}
]);

/**
 * \`eraId|NAME\` → continent, for the handful of dataset names whose land differs by era
 * (a name two different places have borne, or a polity whose remaining territory moved
 * off a continent between two eras).
 */
export const POLITY_CONTINENT_BY_ERA: ReadonlyMap<string, string> = new Map([
${rows(byEraName)}
]);
`;

writeFileSync(R("../src/data/polityContinents.ts"), out);
console.log(
  `build-polity-continents: ${byName.size} names + ${byEraName.size} era-specific rows written to src/data/polityContinents.ts`,
);
