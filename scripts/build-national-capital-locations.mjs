// Generates src/data/nationalCapitalLocations.ts — for each national capital,
// the ISO 3166-2 subdivision whose polygon geographically CONTAINS it, decided
// by point-in-polygon against the app's own public/subdivisions/{CC}.json (the
// same "geography decides" discipline as build-cities.mjs). The hierarchy chart
// uses this to place a national capital that heads no subdivision (Ottawa,
// Pretoria …) as a capital leaf UNDER the subdivision it sits in, alongside that
// subdivision's own capital. Never hand-write an entry — re-run this script.
//
//   node scripts/build-national-capital-locations.mjs
//
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const CITIES_TS = resolve(ROOT, "src/data/cities.ts");
const SUBDIV_DIR = resolve(ROOT, "public/subdivisions");
const OUT = resolve(ROOT, "src/data/nationalCapitalLocations.ts");

// --- point-in-polygon (identical to build-cities.mjs) -----------------------
function pointInRing(pt, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1];
    const xj = ring[j][0], yj = ring[j][1];
    const hit =
      yi > pt[1] !== yj > pt[1] &&
      pt[0] < ((xj - xi) * (pt[1] - yi)) / (yj - yi) + xi;
    if (hit) inside = !inside;
  }
  return inside;
}
function pointInPolygon(pt, rings) {
  if (!pointInRing(pt, rings[0])) return false;
  for (let k = 1; k < rings.length; k++) if (pointInRing(pt, rings[k])) return false;
  return true;
}
function pointInGeometry(pt, geom) {
  if (!geom) return false;
  if (geom.type === "Polygon") return pointInPolygon(pt, geom.coordinates);
  if (geom.type === "MultiPolygon") return geom.coordinates.some((p) => pointInPolygon(pt, p));
  return false;
}

// --- read NATIONAL_CITIES coordinates straight from the generated cities.ts --
const src = readFileSync(CITIES_TS, "utf8");
const block = src.match(/export const NATIONAL_CITIES[^{]*\{([\s\S]*?)\n\};/);
if (!block) throw new Error("Could not find NATIONAL_CITIES in cities.ts");
const national = {};
for (const m of block[1].matchAll(/^\s*"([A-Z]{2})":\s*(\{.*\}),?\s*$/gm)) {
  national[m[1]] = JSON.parse(m[2]);
}

const map = {};
for (const [cc, data] of Object.entries(national)) {
  const path = resolve(SUBDIV_DIR, `${cc}.json`);
  if (!existsSync(path)) continue;
  const sub = JSON.parse(readFileSync(path, "utf8"));
  for (const cap of data.capitals ?? []) {
    if (!isFinite(cap.lon) || !isFinite(cap.lat)) continue;
    const feat = sub.features.find((f) => pointInGeometry([cap.lon, cap.lat], f.geometry));
    if (!feat) continue;
    // The subdivision code the maps/meta use: the ISO 3166-2 code where present,
    // else the feature name (some countries — e.g. Madagascar — carry no ISO code
    // and are keyed by name in SUBDIVISION_META). Never uppercase a name.
    const p = feat.properties;
    const code = p.iso_3166_2?.trim().toUpperCase() || p.name_en?.trim() || p.name?.trim();
    if (code) map[`${cc}|${cap.name}`] = code;
  }
}

const entries = Object.keys(map)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/build-national-capital-locations.mjs — do not edit.
//
// For each national capital, the ISO 3166-2 subdivision whose polygon
// geographically CONTAINS it (point-in-polygon against public/subdivisions/*,
// the same "geography decides" rule as the city overlay). Keyed by
// \`<ISO 3166-1 alpha-2>|<capital name>\` (the exact name from NATIONAL_CITIES).
//
// The hierarchy chart uses this to place a national capital that heads no
// subdivision (Ottawa → CA-ON, Pretoria → ZA-GT …) as a capital leaf under the
// subdivision it sits in, level with that subdivision's own capital — never
// fabricated, purely a geometric lookup.
export const NATIONAL_CAPITAL_SUBDIVISION: Record<string, string> = {
${entries}
};
`;
writeFileSync(OUT, out);
console.log(`Wrote ${OUT} with ${Object.keys(map).length} entries.`);
